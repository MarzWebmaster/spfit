import fs from 'node:fs/promises';
import path from 'node:path';
import mysql from 'mysql2/promise';
import mysqlCore from 'mysql2';
import dotenv from 'dotenv';

dotenv.config();

function timestamp() {
  return new Date().toISOString().replace(/[-:TZ.]/g, '').slice(0, 14);
}

function formatDate(value) {
  const iso = value.toISOString();
  return `${iso.slice(0, 10)} ${iso.slice(11, 23)}`;
}

function serializeValue(value) {
  if (value === null || value === undefined) {
    return 'NULL';
  }

  if (Buffer.isBuffer(value)) {
    return `X'${value.toString('hex')}'`;
  }

  if (value instanceof Date) {
    return mysqlCore.escape(formatDate(value));
  }

  if (typeof value === 'object') {
    return mysqlCore.escape(JSON.stringify(value));
  }

  return mysqlCore.escape(value);
}

async function main() {
  const database = process.env.DB_NAME || 'spfit_db';
  // Use BACKUP_PATH if set (should be outside synced/cloud folders e.g. D:\SPFIT_Backups on Windows, /var/backups/spfit on Linux)
  const backupRoot = process.env.BACKUP_PATH
    ? path.resolve(process.env.BACKUP_PATH)
    : path.resolve(process.cwd(), 'temp');
  const outputDir = path.join(backupRoot, 'db-backups');
  const outputFile = path.join(outputDir, `backup_${database}_${timestamp()}.sql`);

  await fs.mkdir(outputDir, { recursive: true });

  const connection = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD || '',
    database,
  });

  try {
    const sqlParts = [
      '-- Backup generated by scripts/backup-mysql-database.mjs',
      `-- Database: ${database}`,
      'SET FOREIGN_KEY_CHECKS=0;',
      'SET UNIQUE_CHECKS=0;',
      '',
    ];

    const [tableRows] = await connection.query('SHOW TABLES');
    const tableKey = `Tables_in_${database}`;
    const tableNames = tableRows.map((row) => row[tableKey]).sort();

    for (const tableName of tableNames) {
      const [createRows] = await connection.query(`SHOW CREATE TABLE \`${tableName}\``);
      const createSql = createRows[0]['Create Table'];
      sqlParts.push(`DROP TABLE IF EXISTS \`${tableName}\`;`);
      sqlParts.push(`${createSql};`);

      const [rows] = await connection.query(`SELECT * FROM \`${tableName}\``);
      if (rows.length > 0) {
        const columns = Object.keys(rows[0]).map((column) => `\`${column}\``).join(', ');
        const values = rows.map((row) => `(${Object.values(row).map(serializeValue).join(', ')})`).join(',\n');
        sqlParts.push(`INSERT INTO \`${tableName}\` (${columns}) VALUES\n${values};`);
      }

      sqlParts.push('');
    }

    sqlParts.push('SET UNIQUE_CHECKS=1;');
    sqlParts.push('SET FOREIGN_KEY_CHECKS=1;');
    sqlParts.push('');

    await fs.writeFile(outputFile, sqlParts.join('\n'), 'utf8');
    console.log(outputFile);
  } finally {
    await connection.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});